#!/usr/bin/env node
/**
 * Generate src/brand/icons.generated.ts — the active brand's PNG icon
 * require-map. Metro needs literal require() paths, so we emit one explicit
 * require per icon/state. Regenerated per APP_BRAND at build time, mirroring
 * scripts/build-tokens.mjs (only the active brand's PNGs are bundled).
 *
 *   APP_BRAND=symply-house npm run icons:build
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brandId = (
  process.env.EXPO_PUBLIC_APP_BRAND ||
  process.env.APP_BRAND ||
  'symply-house'
).trim();

const STATES = [
  { dir: 'selected', key: 'selected' },
  { dir: 'unselected-dark', key: 'unselectedDark' },
  { dir: 'unselected-light', key: 'unselectedLight' },
  { dir: 'filled-accent', key: 'filledAccent' },
];

const pngRoot = path.join(REPO, 'brands', brandId, 'src/assets/icons/png');
const selectedDir = path.join(pngRoot, 'selected');
if (!fs.existsSync(selectedDir)) {
  console.error(
    `No icons for "${brandId}" (missing ${path.relative(REPO, selectedDir)}). ` +
      `Run scripts/import-brand-icon-pngs.mjs first.`
  );
  // Emit an empty map so the app still compiles for brands without a kit yet.
  writeFile({});
  process.exit(0);
}

const names = fs
  .readdirSync(selectedDir)
  .filter(f => /\.png$/i.test(f))
  .map(f => f.replace(/\.png$/i, ''))
  .sort();

const entries = {};
for (const name of names) {
  const states = {};
  for (const { dir, key } of STATES) {
    const abs = path.join(pngRoot, dir, `${name}.png`);
    if (fs.existsSync(abs)) {
      states[key] = `../../brands/${brandId}/src/assets/icons/png/${dir}/${name}.png`;
    }
  }
  entries[name] = states;
}

writeFile(entries);
console.log(`✓ ${brandId}: ${names.length} icons → src/brand/icons.generated.ts`);

function writeFile(entries) {
  const names = Object.keys(entries);
  const body = names
    .map(name => {
      const st = entries[name];
      const parts = Object.entries(st)
        .map(([k, rel]) => `    ${k}: require('${rel}')`)
        .join(',\n');
      return `  ${JSON.stringify(name)}: {\n${parts},\n  }`;
    })
    .join(',\n');

  const out =
    `// GENERATED by scripts/build-brand-icons.mjs (APP_BRAND=${brandId}) — DO NOT EDIT.\n` +
    `// Source: brands/${brandId}/src/assets/icons/png/**. Run: APP_BRAND=${brandId} npm run icons:build\n` +
    `import type { ImageSourcePropType } from 'react-native';\n\n` +
    `export interface BrandIconStates {\n` +
    `  selected: ImageSourcePropType;\n` +
    `  unselectedDark: ImageSourcePropType;\n` +
    `  unselectedLight: ImageSourcePropType;\n` +
    `  filledAccent?: ImageSourcePropType;\n` +
    `}\n\n` +
    `export const brandIconAssets: Record<string, BrandIconStates> = {\n${body}${
      body ? ',\n' : ''
    }};\n\n` +
    `export const brandIconNames = [\n${names
      .map(n => `  ${JSON.stringify(n)}`)
      .join(',\n')}${names.length ? ',' : ''}\n] as const;\n\n` +
    `export type BrandIconName = (typeof brandIconNames)[number];\n`;

  fs.writeFileSync(path.join(REPO, 'src/brand/icons.generated.ts'), out);
}
