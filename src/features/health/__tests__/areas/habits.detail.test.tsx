describe('HealthHabitDetailScreen — 28-day history', () => {
  it('HEALTH-HABIT-408: the accessibility summary counts only DONE days out of 28', async () => {
    const { tree } = await render(habit({ frequency: 'daily', days: [TODAY, '2026-07-12'] }));

    expect(byTestId(tree, 'health-habit-detail-history')[0].props.accessibilityLabel).toBe(
      '2 of the last 28 days completed',
    );
  });

  it('HEALTH-HABIT-409: a weekends-only habit reads mid-week days as "not scheduled" — a THIRD, transparent state, not "missed"', async () => {
    // TODAY (2026-07-13) is a Monday — not scheduled for a weekends-only habit,
    // and never ticked, so most of the 28-day strip must render as the
    // literal `transparent` fill (unscheduled), never the grey "missed" one a
    // plain done/not-done grid would show for every untouched day.
    const theHabit = habit({ frequency: 'weekends', days: [] });
    const { tree } = await render(theHabit);

    const expectedUnscheduled = habitHistory(theHabit, 28, TODAY).filter(
      (d) => !d.scheduled,
    ).length;
    expect(expectedUnscheduled).toBeGreaterThan(0); // sanity: the fixture is meaningful

    // Cells carry no per-day testID (the grid is a plain 28-`View` strip), so
    // they are found by their own fixed geometry (`styles.historyCell`),
    // scoped to host `View`s only.
    const cells = tree.root.findAll(
      (n) =>
        typeof n.type === 'string' &&
        String(n.type) === 'View' &&
        StyleSheet.flatten(n.props?.style)?.width === 22 &&
        StyleSheet.flatten(n.props?.style)?.height === 22,
    );
    const transparentCount = cells.filter(
      (c) => StyleSheet.flatten(c.props.style).backgroundColor === 'transparent',
    ).length;

    expect(cells).toHaveLength(28);
    expect(transparentCount).toBe(expectedUnscheduled);

    expect(allText(tree.toJSON())).toContain(
      'Filled = done · grey = scheduled and missed · outline = not scheduled',
    );
  });
});

