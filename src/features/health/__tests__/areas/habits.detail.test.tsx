describe('HealthHabitDetailScreen — actions', () => {
  it('HEALTH-HABIT-410: the primary button reflects today and toggles it', async () => {
    const { tree: notDone, onToggle } = await render(habit({ days: [] }));
    expect(textOf(notDone, 'health-habit-detail-toggle')).toContain('Mark as complete');

    press(notDone, 'health-habit-detail-toggle');
    expect(onToggle).toHaveBeenCalledWith(expect.objectContaining({ id: 'sleep' }), TODAY);

    const { tree: done } = await render(habit({ days: [TODAY] }));
    expect(textOf(done, 'health-habit-detail-toggle')).toContain('Completed today');
    expect(
      byTestId(done, 'health-habit-detail-toggle')[0].props.accessibilityLabel,
    ).toBe('Mark as not done today');
  });

  it('HEALTH-HABIT-411: Archive / Unarchive labels flip with state and call onArchive with the OPPOSITE flag', async () => {
    const { tree: active, onArchive: archiveIt } = await render(habit({ archived: false }));
    expect(textOf(active, 'health-habit-detail-archive')).toBe('Archive');
    press(active, 'health-habit-detail-archive');
    expect(archiveIt).toHaveBeenCalledWith(expect.objectContaining({ id: 'sleep' }), true);

    const { tree: archived, onArchive: unarchiveIt } = await render(habit({ archived: true }));
    expect(textOf(archived, 'health-habit-detail-archive')).toBe('Unarchive');
    press(archived, 'health-habit-detail-archive');
    expect(unarchiveIt).toHaveBeenCalledWith(expect.objectContaining({ id: 'sleep' }), false);
  });

  it('HEALTH-HABIT-412: Edit opens the real form seeded from the habit, and toggles its own label', async () => {
    const { tree } = await render(
      habit({ name: 'Stretch', notes: 'after the school run', frequency: 'weekdays' }),
    );

    expect(byTestId(tree, 'health-habit-edit-form')).toHaveLength(0);
    expect(textOf(tree, 'health-habit-detail-edit')).toBe('Edit');

    press(tree, 'health-habit-detail-edit');

    expect(byTestId(tree, 'health-habit-edit-form')).toHaveLength(1);
    expect(input(tree, 'health-habit-edit-name').props.value).toBe('Stretch');
    expect(textOf(tree, 'health-habit-detail-edit')).toBe('Close');
    // Editing hides the notes card — the form's own NOTES field is the one
    // editable copy on screen; a second, stale one would be confusing.
    expect(byTestId(tree, 'health-habit-detail-notes')).toHaveLength(0);

    // Pressing it again (without submitting) closes it, discarding nothing
    // because nothing was sent.
    press(tree, 'health-habit-detail-edit');
    expect(byTestId(tree, 'health-habit-edit-form')).toHaveLength(0);
  });

  it('HEALTH-HABIT-413: submitting the edit form calls onSave with the habit and the draft, and closes the editor', async () => {
    const { tree, onSave } = await render(habit({ name: 'Stretch' }));
    press(tree, 'health-habit-detail-edit');

    type(tree, 'health-habit-edit-name', 'Evening stretch');
    press(tree, 'health-habit-edit-submit');

    expect(onSave).toHaveBeenCalledWith(
      expect.objectContaining({ id: 'sleep' }),
      expect.objectContaining({ name: 'Evening stretch' }),
    );
    expect(byTestId(tree, 'health-habit-edit-form')).toHaveLength(0);
  });

  it('HEALTH-HABIT-414: Cancel on the edit form closes it without calling onSave', async () => {
    const { tree, onSave } = await render(habit());
    press(tree, 'health-habit-detail-edit');

    press(tree, 'health-habit-edit-cancel');

    expect(onSave).not.toHaveBeenCalled();
    expect(byTestId(tree, 'health-habit-edit-form')).toHaveLength(0);
  });
});

