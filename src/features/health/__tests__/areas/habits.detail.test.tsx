describe('HealthHabitDetailScreen — header', () => {
  it('HEALTH-HABIT-400: shows category · time-of-day, the schedule in words, and the reminder line', async () => {
    const { tree } = await render(
      habit({
        category: 'fitness',
        timeOfDay: 'morning',
        frequency: 'weekdays',
        reminderEnabled: true,
        reminderTime: '07:00',
      }),
    );

    expect(allText(tree.toJSON())).toContain('Fitness · Morning');
    expect(textOf(tree, 'health-habit-detail-schedule')).toBe('Monday to Friday');
    expect(allText(tree.toJSON())).toContain('Reminder at 07:00');
  });

  it('HEALTH-HABIT-401: no reminder set (or disabled) reads "No reminder"', async () => {
    const { tree: off } = await render(habit({ reminderEnabled: false, reminderTime: '07:00' }));
    expect(allText(off.toJSON())).toContain('No reminder');

    const { tree: noTime } = await render(habit({ reminderEnabled: true, reminderTime: null }));
    expect(allText(noTime.toJSON())).toContain('No reminder');
  });

  it('HEALTH-HABIT-402: an archived habit shows the banner; an active one does not', async () => {
    const { tree: archived } = await render(habit({ archived: true }));
    expect(byTestId(archived, 'health-habit-detail-archived')).toHaveLength(1);

    const { tree: active } = await render(habit({ archived: false }));
    expect(byTestId(active, 'health-habit-detail-archived')).toHaveLength(0);
  });

  it('HEALTH-HABIT-403: Close fires onClose', async () => {
    const { tree, onClose } = await render(habit());
    press(tree, 'health-habit-detail-close');
    expect(onClose).toHaveBeenCalledTimes(1);
  });

  it('HEALTH-HABIT-403b: a habit with no icon of its own falls back to its CATEGORY icon', async () => {
    // A custom habit created before an icon was chosen (or one whose column
    // came back blank from the server) must still draw something on-brand
    // rather than an empty tile — the category's own icon.
    const { tree } = await render(habit({ icon: '', category: 'fitness' }));

    // Size 28 is unique to the header identity icon in this render (the close
    // button is 20, every action/stat icon smaller still).
    const identityIcon = tree.root.findAllByType(Icon).find((n) => n.props.size === 28);
    expect(identityIcon?.props.name).toBe(categoryIcon('fitness'));
  });
});

