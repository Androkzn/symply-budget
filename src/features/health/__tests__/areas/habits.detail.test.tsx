/**
 * Concatenated text of a subtree, with the icon primitive's own subtree skipped.
 *
 * `<Icon>` resolves a name against the active brand's PNG kit
 * (`src/brand/icons.generated.ts` — GENERATED, regenerated by `icons:build` for
 * whichever APP_BRAND is being built) and falls through to `<Ionicons>` when
 * that kit has no such slug. The PNG branch contributes no text; the Ionicons
 * branch renders a `<Text>` holding a glyph codepoint — or a literal "?" when
 * the name is not an Ionicons slug either. Health's `history`, `streak`,
 * `sleep-habit`, … exist in `brands/symply-health` but not in the
 * `brands/symply-house` kit Jest pins, so the icon beside a button label leaked
 * into that label ("?Unarchive"). Labels are what these assertions are about,
 * so glyphs are excluded rather than absorbed.
 */
function allText(node: unknown): string {
  if (node == null) return '';
  if (typeof node === 'string') return node;
  if (typeof node === 'number') return String(node);
  if (Array.isArray(node)) return node.map(allText).join('');
  if ((node as { type?: unknown }).type === Icon) return '';
  return allText((node as { children?: unknown }).children);
}

function byTestId(tree: Rendered, id: string) {
  return tree.root.findAll((n) => typeof n.type === 'string' && n.props?.testID === id);
}

function textOf(tree: Rendered, id: string): string {
  const node = byTestId(tree, id)[0];
  if (!node) return '';
  // An <Icon> that falls back to Ionicons renders as TEXT — an icon-font
  // codepoint in the Private Use Area — so a button with a leading glyph reads
  // as " Unarchive" and never equals its label. Drop PUA characters (and
  // the "?" a missing glyph renders as) so this returns the words on screen.
  return allText(node)
    .replace(/[-]/g, '')
    .replace(/^\?+/, '')
    .trim();
}

/** `HealthStatTiles` puts label AND value under one testID; read the a11y label instead. */
function statLabelOf(tree: Rendered, id: string): string {
  return byTestId(tree, id)[0]?.props.accessibilityLabel ?? '';
}

/** The composite carrying `testID` (the Pressable, not its host View). */
function pressable(tree: Rendered, testID: string) {
  return tree.root.find((n) => n.props?.testID === testID && typeof n.props?.onPress === 'function');
}

function press(tree: Rendered, testID: string) {
  act(() => pressable(tree, testID).props.onPress());
}

function input(tree: Rendered, testID: string) {
  return tree.root.find(
    (n) => (n.type as unknown as string) === 'TextInput' && n.props?.testID === testID,
  );
}

function type(tree: Rendered, testID: string, text: string) {
  act(() => input(tree, testID).props.onChangeText(text));
}

interface Callbacks {
  onClose: jest.Mock;
  onToggle: jest.Mock;
  onSave: jest.Mock;
  onArchive: jest.Mock;
  onDelete: jest.Mock;
}

async function render(theHabit: Habit, overrides: Partial<HealthHabitDetailScreenProps> = {}) {
  const callbacks: Callbacks = {
    onClose: jest.fn(),
    onToggle: jest.fn(),
    onSave: jest.fn(),
    onArchive: jest.fn(),
    onDelete: jest.fn(),
  };
  let tree!: Rendered;
  await act(async () => {
    tree = ReactTestRenderer.create(
      <ThemeProvider>
        <HealthHabitDetailScreen habit={theHabit} {...callbacks} {...overrides} />
      </ThemeProvider>,
    );
  });
  return { tree, ...callbacks };
}

