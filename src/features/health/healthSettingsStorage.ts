/** Every flag that is NOT a delivery switch — i.e. the per-event toggles. */
export const HEALTH_ACTIVITY_EVENT_FLAGS: readonly HealthActivityPreferenceFlag[] =
  HEALTH_NOTIFICATION_GROUPS.filter((group) => group.id !== 'delivery').flatMap((group) =>
    group.toggles.map((toggle) => toggle.flag)
  );

/* ==================================================================== */
/* Read / write                                                          */
/* ==================================================================== */

function coerce(value: unknown): HealthNotificationPreferences {
  const source = (value ?? {}) as Partial<Record<HealthActivityPreferenceFlag, unknown>>;
  const prefs = { ...DEFAULT_HEALTH_NOTIFICATION_PREFERENCES };
  for (const flag of HEALTH_ACTIVITY_PREFERENCE_FLAGS) {
    // The Worker stores INTEGER 0/1 and answers booleans; a cached snapshot from
    // an older build (or a hand-edited one) can be anything at all. Anything
    // that is not a boolean falls back to the donor default rather than being
    // coerced, so a truthy `1` cannot masquerade as a deliberate choice.
    if (typeof source[flag] === 'boolean') prefs[flag] = source[flag] as boolean;
  }
  return prefs;
}

async function fetchNotificationPreferences(): Promise<HealthNotificationPreferences> {
  const payload = await healthApi.activityPreferences();
  return coerce(payload?.preferences);
}

/** Read-through: the cache renders instantly, a successful read replaces it. */
export async function loadNotificationPreferences(): Promise<HealthNotificationPreferences> {
  const prefs = await readThrough(HEALTH_NOTIFY_PREFS_KEY, fetchNotificationPreferences, {
    ...DEFAULT_HEALTH_NOTIFICATION_PREFERENCES,
  });
  return coerce(prefs);
}

export interface HealthNotificationWriteResult {
  preferences: HealthNotificationPreferences;
  status: 'saved' | 'offline';
  /** Friendly copy, or null when there is nothing to say. Never a raw error. */
  message: string | null;
}

export const NOTIFY_PREFS_OFFLINE_MESSAGE =
  'Saved on this device — we will sync it to your account when you are back online.';

/**
 * PATCH one or more flags.
 *
 * Only the changed keys are sent: the route merges server-side, so a client
 * that posted the whole object would overwrite a flag a newer build knows about
 * and this one does not.
 */
export async function saveNotificationPreferences(
  patch: Partial<HealthNotificationPreferences>
): Promise<HealthNotificationWriteResult> {
  const before = await loadNotificationPreferences();
  const optimistic = coerce({ ...before, ...patch });
  try {
    const payload = await healthApi.saveActivityPreferences(patch);
    const preferences = coerce(payload?.preferences ?? optimistic);
    await storageHelpers.setObject(HEALTH_NOTIFY_PREFS_KEY, preferences);
    return { preferences, status: 'saved', message: null };
  } catch {
    // The member's own choice is kept and shown back to them: this is a
    // preference, not a health record, and the next successful read replaces the
    // cache wholesale. No error string ever reaches the UI.
    await storageHelpers.setObject(HEALTH_NOTIFY_PREFS_KEY, optimistic);
    return { preferences: optimistic, status: 'offline', message: NOTIFY_PREFS_OFFLINE_MESSAGE };
  }
}

/** Donor's "Reset to Defaults" — sends all ten explicitly, never a bare PUT. */
export async function resetNotificationPreferences(): Promise<HealthNotificationWriteResult> {
  return saveNotificationPreferences({ ...DEFAULT_HEALTH_NOTIFICATION_PREFERENCES });
}

/** One-line summary for the "More" row subtitle. */
export function describeNotificationPreferences(prefs: HealthNotificationPreferences): string {
  const delivery = prefs.receive_push_notifications
    ? 'Push on'
    : prefs.receive_inapp_notifications
      ? 'In-app only'
      : 'All off';
  const on = HEALTH_ACTIVITY_EVENT_FLAGS.filter((flag) => prefs[flag]).length;
  return `${delivery} · ${on} of ${HEALTH_ACTIVITY_EVENT_FLAGS.length} activity alerts`;
}
