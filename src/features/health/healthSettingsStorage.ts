/**
 * Symply Health — the ACTIVITY NOTIFICATION preferences (donor
 * `ActivityNotificationPreferencesView`).
 *
 * Record of truth: `PUT /health/activity-preferences` on the
 * `symply-health-api` Worker (`backend/src/routes/health-body-extras.ts`). Ten
 * booleans have been deployed there since P2 with, until this module, zero
 * callers — the screen that owned them in the donor was never ported, so the
 * only way to change them was a hand-written request.
 *
 * MMKV is an offline read-through cache exactly as in every other Health store,
 * never the record (see `healthRepository`).
 *
 * ## What these switches DO and DO NOT do today — read before changing the copy
 *
 * They are stored, they are per-account, and they sync across the member's
 * devices. They do NOT yet gate a send: nothing on this Worker reads them (grep
 * `receive_push_notifications` outside the route + schema and you find only
 * tests), because the donor features that produce these events — family recipe
 * sharing, shared workout videos, shared progress photos, the buddy community —
 * are not part of the Symply Health port.
 *
 * That is why {@link HEALTH_NOTIFICATION_GROUPS} carries a `disclosure` string
 * per group and the screen renders it. A settings screen that silently implies
 * "turn this off and we will stop sending you X" when nothing sends X is the
 * kind of quiet lie this app does not ship. The switches are still real: the
 * member's choice is recorded now and applies the moment a producer lands.
 */

/* ==================================================================== */
/* Cache key                                                             */
/* ==================================================================== */

/**
 * MUST be registered in `healthCacheKeys.ts` (it is) — these flags are an
 * account-level preference, so a copy left behind on sign-out would show the
 * next person on the handset the previous member's choices.
 */
